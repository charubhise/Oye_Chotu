def filter_by_criteria(
    products: List[Dict[str, Any]],
    requested_type: Optional[str] = None,
    requested_color: Optional[str] = None,
    category: Optional[str] = None,
    max_price: Optional[int] = None,
    min_price: Optional[int] = None,
    sort_by: Optional[str] = None,
    query: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Applies STRICT filtering priority:
    1. Match requested product type (e.g. kurti, shoes, headphones).
    2. Match requested category (e.g. fashion, electronics).
    3. Match requested colour (e.g. black, red, blue).
       Never return red shoes when user asks for black shoes!
    4. Apply requested price limits (max_price, min_price).
    5. Check product availability (in_stock).
    
    Returns a dict with:
      - 'exact_matches': List[Dict[str, Any]] (ONLY items matching all criteria!)
      - 'other_colors': List[Dict[str, Any]] (Separate recommendations in other colors, never mixed!)
      - 'message': str
    """
    exact: List[Dict[str, Any]] = []

    for p in products:
        if not p.get("in_stock", True):
            continue

        # Priority 1: Requested product type (strict)
        if requested_type:
            prod_type = (p.get("product_type") or "").lower()
            if prod_type != requested_type.lower():
                continue

        # Priority 2: Requested category (if given)
        if category:
            if (p.get("category") or "").lower() != category.lower():
                continue

        # Priority 3: Requested colour (STRICT! NEVER mix colours!)
        if requested_color:
            prod_color = (p.get("color") or "").lower()
            if prod_color != requested_color.lower():
                continue

        # Priority 4: Price limits (strict)
        price = p.get("price", 0)
        if max_price is not None and price > max_price:
            continue
        if min_price is not None and price < min_price:
            continue

        # Fallback text query match ONLY when neither type nor color was extracted
        if query and not requested_type and not requested_color and not category:
            q = query.lower().strip()
            text_corpus = (
                p["name"].lower() + " " +
                p.get("marathi_name", "").lower() + " " +
                p.get("hindi_name", "").lower() + " " +
                p.get("description", "").lower() + " " +
                " ".join(p.get("tags", [])).lower()
            )
            words = [w for w in q.split() if len(w) > 2]
            if words and not all(w in text_corpus for w in words):
                continue

        exact.append(p)

    # Sort exact matches
    if sort_by == "price_asc":
        exact.sort(key=lambda x: x["price"])
    elif sort_by == "price_desc":
        exact.sort(key=lambda x: x["price"], reverse=True)
    elif sort_by == "rating":
        exact.sort(key=lambda x: x["rating"], reverse=True)

    # Build other colours suggestions separately (only when a color was requested)
    other_colors: List[Dict[str, Any]] = []
    if requested_color and (requested_type or category):
        for p in products:
            if not p.get("in_stock", True):
                continue
            if requested_type and (p.get("product_type") or "").lower() != requested_type.lower():
                continue
            if category and (p.get("category") or "").lower() != category.lower():
                continue
            if (p.get("color") or "").lower() == requested_color.lower():
                continue
            if max_price is not None and p.get("price", 0) > max_price:
                continue
            other_colors.append(p)

    return {
        "exact_matches": exact,
        "other_colors": other_colors[:6],
        "count": len(exact),
    }


def find_cheaper_alternatives(current_products: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Returns products sorted by lowest price, prioritizing items within the same type/category."""
    if not current_products:
        catalog = PRODUCTS_DATA
    else:
        ptype = current_products[0].get("product_type")
        same_type = [p for p in PRODUCTS_DATA if p.get("product_type") == ptype]
        if same_type and len(same_type) > 1:
            catalog = same_type
        else:
            cat = current_products[0].get("category")
            same_cat = [p for p in PRODUCTS_DATA if p.get("category") == cat]
            catalog = same_cat if same_cat else PRODUCTS_DATA

    return sorted(catalog, key=lambda x: x["price"])
